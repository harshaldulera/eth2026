/**
 * Compile contracts/src/SiegeVault.sol with solc-js (no Foundry needed) and write
 * lib/chain/abi/SiegeVault.ts with a typed `as const` ABI and the deploy bytecode.
 *   npm run abi
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
// eslint-disable-next-line @typescript-eslint/no-require-imports
const solc = require("solc");

const root = path.resolve(process.cwd(), "..", "contracts");
const source = readFileSync(path.join(root, "src", "SiegeVault.sol"), "utf8");

const input = {
  language: "Solidity",
  sources: { "SiegeVault.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
for (const e of out.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);

const c = out.contracts["SiegeVault.sol"].SiegeVault;
const dest = path.join(process.cwd(), "lib", "chain", "abi");
mkdirSync(dest, { recursive: true });
writeFileSync(
  path.join(dest, "SiegeVault.ts"),
  `// Generated by scripts/compile-contracts.ts from contracts/src/SiegeVault.sol (solc ${solc.version()}). Do not edit.\n` +
    `export const siegeVaultAbi = ${JSON.stringify(c.abi, null, 2)} as const;\n\n` +
    `export const siegeVaultBytecode = "0x${c.evm.bytecode.object}" as const;\n`,
);
console.log(`wrote lib/chain/abi/SiegeVault.ts (${c.evm.bytecode.object.length / 2} bytes)`);
